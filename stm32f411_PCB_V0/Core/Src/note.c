#define NOTE_COUNT (sizeof(note_table)/sizeof(NoteEntry))


float Note_GetFrequency(const char* name)
{

    for (int i = 0;i < NOTE_COUNT;i++)
    {
        if (strcmp(note_table[i].name, name) == 0)
        {
            return note_table[i].frequency;
        }
    }


    // note inconnue
    return 0.0f;
}
